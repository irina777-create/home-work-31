// # Домашнє завдання: ланцюжок промісів «Оформлення замовлення»
//
// **Сценарій.** Користувач оформлює замовлення в інтернет-магазині. Спочатку магазин перевіряє, чи є товар на складі, потім проводить оплату. Якщо щось пішло не так, користувач бачить причину помилки.
//
// ## Що потрібно зробити
//
// 1. Створити проміс `checkStock`. Усередині:
// - вивести в консоль `Перевіряємо наявність товару...`;
// - через **1 секунду** показати `confirm("Товар є в наявності?")`;
// - якщо «ОК», викликати `resolve()`;
// - якщо «Скасувати», викликати `reject("Товару немає в наявності")`.
//
// 2. Побудувати ланцюжок рівно з **двох `.then()`** і **одного `.catch()`**:
// - **Перший `.then()`**:
// - виводить `🟢 Товар є в наявності`;
// - показує `confirm("Оплата пройшла успішно?")`;
// - якщо оплата не пройшла, робить `return Promise.reject("Оплату відхилено банком")`.
// - **Другий `.then()`**: виводить `🥳 Замовлення оформлено!`.
// - **`.catch()`** приймає причину помилки й виводить `🔴 Замовлення не оформлено: <причина>`.
//
// ## Очікуваний результат у консолі
//
// - **Товар є, оплата пройшла** (ОК → ОК):
// `🟢 Товар є в наявності` → `🥳 Замовлення оформлено!`
// - **Товар є, оплата не пройшла** (ОК → Скасувати):
// `🟢 Товар є в наявності` → `🔴 Замовлення не оформлено: Оплату відхилено банком`
// - **Товару немає** (Скасувати, другий `confirm` не з'являється):
//     `🔴 Замовлення не оформлено: Товару немає в наявності`
const checkStock = new Promise((resolve, reject) => {
    console.log('Перевіряємо наявність товару...');

    setTimeout(() => {
        const isInStock = confirm('Товар є в наявності?');

        if (isInStock) {
            resolve();
        } else {
            reject('Товару немає в наявності');
        }
    }, 1000);
});

checkStock
    .then(() => {
        console.log('🟢 Товар є в наявності');

        const isPaymentSuccessful = confirm('Оплата пройшла успішно?');

        if (!isPaymentSuccessful) {
            return Promise.reject('Оплату відхилено банком');
        }
    })
    .then(() => {
        console.log('🥳 Замовлення оформлено!');
    })
    .catch((reason) => {
        console.log(`🔴 Замовлення не оформлено: ${reason}`);
    });